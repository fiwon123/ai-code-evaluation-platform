import { render, screen } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import SharedResultPage from "../SharedResultPage.tsx";

const fetchMock = vi.fn();

function renderPage(token = "share-token-123") {
  return render(
    <MemoryRouter initialEntries={[`/results/${token}`]}>
      <Routes>
        <Route path="/results/:token" element={<SharedResultPage />} />
      </Routes>
    </MemoryRouter>,
  );
}

describe("SharedResultPage", () => {
  beforeEach(() => {
    vi.stubGlobal("fetch", fetchMock);
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    vi.clearAllMocks();
  });

  it("renders the shared report without authentication", async () => {
    const shared = {
      challenge_id: "c1",
      challenge_title: "Two Sum",
      challenge_prompt: "Write two_sum(nums, target).",
      language: "python",
      provider: "demo",
      status: "completed",
      created_at: "2026-01-01T00:00:00Z",
      code: "def two_sum(nums, target):\n    return [0, 1]\n",
      score: 90,
      passed_tests: 2,
      total_tests: 2,
      logs: "2 passed in 0.01s",
      metrics: { duration_ms: 12, language: "python" },
      test_results: [
        { name: "test_two_sum", passed: true, message: null },
        { name: "test_edge_case", passed: false, message: "boom" },
      ],
    };
    fetchMock.mockResolvedValueOnce(
      new Response(JSON.stringify(shared), { status: 200 }),
    );

    renderPage();

    // Fetched the public endpoint with the token from the URL.
    expect(await screen.findByRole("heading", { name: "Two Sum" })).toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledWith(
      "http://localhost:8000/api/results/share-token-123",
      expect.objectContaining({}),
    );

    expect(screen.getByText("Write two_sum(nums, target).")).toBeInTheDocument();
    expect(screen.getByText("90%")).toBeInTheDocument();
    expect(screen.getByText("2/2")).toBeInTheDocument();
    expect(screen.getByText("test_two_sum")).toBeInTheDocument();
    expect(screen.getByText("boom")).toBeInTheDocument();
    expect(screen.getByText(/def two_sum/)).toBeInTheDocument();
    expect(screen.getByText(/12ms/)).toBeInTheDocument();
    expect(
      screen.getByRole("link", {
        name: "Shared evaluation report · generated by AI Code Evaluation Platform",
      }),
    ).toHaveAttribute("href", "/");
  });

  it("shows a helpful message when the token is unknown", async () => {
    fetchMock.mockResolvedValueOnce(
      new Response(JSON.stringify({ detail: "Shared result not found" }), {
        status: 404,
      }),
    );

    renderPage("expired-token");

    expect(await screen.findByRole("alert")).toHaveTextContent(
      "Shared result not found",
    );
    expect(screen.getByRole("link", { name: "Back to the platform" })).toHaveAttribute(
      "href",
      "/",
    );
  });
});