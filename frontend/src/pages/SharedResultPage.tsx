import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import Badge from "../components/Badge/Badge.tsx";
import Card from "../components/Card/Card.tsx";
import PageTitle from "../components/PageTitle/PageTitle.tsx";
import ResultReport from "../components/ResultReport/ResultReport.tsx";
import Skeleton from "../components/Skeleton/Skeleton.tsx";
import { resultsApi } from "../services/api.ts";
import type { SharedResult } from "../types.ts";
import { extractError } from "../utils/errors.ts";
import { statusVariant } from "../utils/formatting.ts";
import styles from "./SharedResultPage.module.css";

const PUBLIC_TITLE = "Shared evaluation report";

/**
 * Public report page — the destination of a share link. No login required,
 * so recruiters and reviewers can open an evaluation without an account.
 */
function SharedResultPage() {
  const { token } = useParams<{ token: string }>();
  const [result, setResult] = useState<SharedResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!token) {
      setError("Missing share token.");
      setLoading(false);
      return;
    }
    let cancelled = false;
    resultsApi
      .getByToken(token)
      .then((data) => {
        if (cancelled) {
          return;
        }
        setResult(data);
        setLoading(false);
      })
      .catch((err) => {
        if (!cancelled) {
          setError(extractError(err));
          setLoading(false);
        }
      });
    return () => {
      cancelled = true;
    };
  }, [token]);

  if (loading) {
    return (
      <div role="status" aria-label="Loading shared report">
        <Skeleton variant="text" width="40%" height="1.5rem" />
        <Skeleton variant="rect" width="100%" height="180px" />
      </div>
    );
  }

  if (error || !result) {
    return (
      <div className={styles.page}>
        <p role="alert" className={styles.errorText}>
          {error ?? "This shared report is no longer available."}
        </p>
        <p>
          <Link to="/">Back to the platform</Link>
        </p>
      </div>
    );
  }

  return (
    <div className={styles.page}>
      <p className={styles.breadcrumb}>
        <Link to="/">AI Code Evaluation Platform</Link> — shared report
      </p>

      <div className={styles.header}>
        <PageTitle className={styles.title}>{result.challenge_title}</PageTitle>
        <Badge variant={statusVariant(result.status)}>{result.status}</Badge>
      </div>

      <Card>
        <p className={styles.promptLabel}>Challenge</p>
        <p className={styles.prompt}>{result.challenge_prompt}</p>
        <p className={styles.meta}>
          Evaluated with <code>{result.provider}</code> ·{" "}
          <code>{result.language}</code> ·{" "}
          {new Date(result.created_at).toLocaleString()}
        </p>
      </Card>

      <ResultReport
        result={result}
        code={result.code}
        language={result.language}
        status={result.status}
      />

      <p className={styles.footer}>
        <Link to="/">{PUBLIC_TITLE} · generated by AI Code Evaluation Platform</Link>
      </p>
    </div>
  );
}

export default SharedResultPage;